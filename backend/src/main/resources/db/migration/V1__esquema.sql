CREATE TABLE productos (
    gtin                 VARCHAR(18)   PRIMARY KEY,
    tipo                 VARCHAR(10)   NOT NULL,
    marca                VARCHAR(120),
    nombre               VARCHAR(200)  NOT NULL,
    contenido            VARCHAR(60),
    precio               NUMERIC(10,2),
    imagen_url           VARCHAR(500),
    gtin_contenido       VARCHAR(14),
    unidades_por_empaque INTEGER,
    fuente               VARCHAR(20)   NOT NULL,
    creado_en            TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE ventas (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha     TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    articulos INTEGER       NOT NULL,
    total     NUMERIC(12,2) NOT NULL
);

CREATE TABLE venta_items (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venta_id        BIGINT        NOT NULL REFERENCES ventas(id) ON DELETE CASCADE,
    gtin            VARCHAR(18)   NOT NULL,
    marca           VARCHAR(120),
    nombre          VARCHAR(200)  NOT NULL,
    precio_unitario NUMERIC(10,2) NOT NULL,
    cantidad        INTEGER       NOT NULL,
    subtotal        NUMERIC(12,2) NOT NULL
);

CREATE INDEX idx_venta_items_venta ON venta_items(venta_id);

CREATE TABLE intentos_escaneo (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo   VARCHAR(40),
    tipo     VARCHAR(12),
    material VARCHAR(40)  NOT NULL,
    exito    BOOLEAN      NOT NULL,
    nota     VARCHAR(200),
    fecha    TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX idx_intentos_material ON intentos_escaneo(material);
